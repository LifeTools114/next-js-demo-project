/** 키워드로 시드 데이터를 검색합니다. (쿠팡 검색 API 대체) */
export function searchSeed(keyword = '', limit = 50) {
  if (!keyword) return SEED_PRODUCTS.slice(0, limit)
  const q = keyword.toLowerCase().replace(/\s+/g, '')
  return SEED_PRODUCTS.filter((p) =>
    `${p.productName}${p.categoryName}`.toLowerCase().replace(/\s+/g, '').includes(q),
  ).slice(0, limit)
}
